function dump(obj) {
  const lines = Object.entries(obj).map(([k, v]) => {
    const esc = JSON.stringify(v)
    return `  ${JSON.stringify(k)}: ${esc},`
  })
  return `/** Auto-generated service-page strings. Do not hand-edit lightly. */\nexport default {\n${lines.join('\n')}\n}\n`
}

const missing = Object.keys(en).filter((k) => !(k in te))
const extra = Object.keys(te).filter((k) => !(k in en))
if (missing.length || extra.length) {
  console.error('Key mismatch', { missing, extra })
  process.exit(1)
}

writeFileSync(join(root, 'src/i18n/services-en.js'), dump(en))
writeFileSync(join(root, 'src/i18n/services-te.js'), dump(te))
console.log(`Wrote ${Object.keys(en).length} keys × 2`)
