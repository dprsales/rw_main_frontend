function dump(obj) {
  const lines = Object.entries(obj).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  return `/** Auto-generated content-page strings. */\nexport default {\n${lines.join('\n')}\n}\n`
}

