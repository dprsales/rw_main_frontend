function dump(obj) {
  const lines = Object.entries(obj).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  return `export default {\n${lines.join('\n')}\n}\n`
}

const enPath = join(root, 'src/i18n/coach-checkout-en.js')
const tePath = join(root, 'src/i18n/coach-checkout-te.js')
writeFileSync(enPath, dump(en))
writeFileSync(tePath, dump(te))
const missing = Object.keys(en).filter((k) => !(k in te))
const extra = Object.keys(te).filter((k) => !(k in en))
console.log(`keys ${Object.keys(en).length}`)
if (missing.length || extra.length) {
  console.error('key mismatch', { missing, extra })
  process.exit(1)
}
